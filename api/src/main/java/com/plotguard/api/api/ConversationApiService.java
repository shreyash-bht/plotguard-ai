package com.plotguard.api.api;

import com.plotguard.api.ai.AiChatClient;
import com.plotguard.api.dto.ChatMessageRequestDto;
import com.plotguard.api.dto.ChatRequestDto;
import com.plotguard.api.dto.ChatResponseDto;
import com.plotguard.api.dto.NewConversationDto;
import com.plotguard.api.dto.UpdateConversationDto;
import com.plotguard.api.entity.Conversation;
import com.plotguard.api.repository.ContentRepository;
import com.plotguard.api.repository.ConversationRepository;
import com.plotguard.api.repository.MessageRepository;
import jakarta.persistence.EntityNotFoundException;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import javax.naming.directory.InvalidAttributesException;
import java.util.List;
import java.util.UUID;

@Service
public class ConversationApiService {
    @Autowired
    private ConversationRepository conversationRepository;

    @Autowired
    private ContentRepository contentRepository;

    @Autowired
    private MessageRepository messageRepository;

    @Autowired
    private AiChatClient aiChatClient;

    @Transactional
    public Conversation createConversation(NewConversationDto newConversationDto, UUID userId)
            throws InvalidAttributesException {
        if (newConversationDto.getConversationId() != null)
            throw new InvalidAttributesException("Conversation ID must not be provided; it is generated by the database");
        if (newConversationDto.getContentId() == null)
            throw new InvalidAttributesException("Content ID must be provided");
        if (newConversationDto.getMaxStoryOrder() == null)
            throw new InvalidAttributesException("Max story order must be provided");
        if (!contentRepository.existsById(newConversationDto.getContentId()))
            throw new EntityNotFoundException("Content with given ID does not exist");
        Conversation newConversation = Conversation.builder()
                .userId(userId)
                .contentId(newConversationDto.getContentId())
                .maxStoryOrder(newConversationDto.getMaxStoryOrder())
                .build();
        return conversationRepository.save(newConversation);
    }

    @Transactional(readOnly = true)
    public List<Conversation> getConversations(UUID userId) {
        return conversationRepository.findAllByUserIdOrderByUpdatedAtDesc(userId);
    }

    @Transactional(readOnly = true)
    public Conversation getConversation(UUID conversationId, UUID userId) {
        return getConversationForUser(conversationId, userId);
    }

    @Transactional
    public Conversation updateConversation(
            UUID conversationId,
            UpdateConversationDto updateConversationDto,
            UUID userId) throws InvalidAttributesException {
        if (updateConversationDto.getMaxStoryOrder() == null)
            throw new InvalidAttributesException("Max story order must be provided");
        Conversation conversation = getConversationForUser(conversationId, userId);
        conversation.setMaxStoryOrder(updateConversationDto.getMaxStoryOrder());
        return conversationRepository.save(conversation);
    }

    @Transactional
    public void deleteConversation(UUID conversationId, UUID userId) {
        Conversation conversation = getConversationForUser(conversationId, userId);
        messageRepository.deleteAllByConversationId(conversation.getConversationId());
        conversationRepository.delete(conversation);
    }

    public ChatResponseDto chat(
            UUID conversationId,
            UUID userId,
            ChatMessageRequestDto chatRequest) throws InvalidAttributesException {
        if (chatRequest == null || chatRequest.userQuestion() == null
                || chatRequest.userQuestion().isBlank())
            throw new InvalidAttributesException("User question must not be blank");

        Conversation conversation = getConversationForUser(conversationId, userId);
        int maxStoryOrder = chatRequest.maxStoryOrder() != null
                ? chatRequest.maxStoryOrder()
                : conversation.getMaxStoryOrder();
        if (maxStoryOrder < 0)
            throw new InvalidAttributesException("Max story order must not be negative");

        ChatRequestDto aiRequest = new ChatRequestDto(
                conversation.getConversationId().toString(),
                conversation.getContentId().toString(),
                maxStoryOrder,
                chatRequest.userQuestion(),
                Boolean.TRUE.equals(chatRequest.isSendMetadata()),
                chatRequest.enableReranking()
        );
        return aiChatClient.chat(aiRequest);
    }

    private Conversation getConversationForUser(UUID conversationId, UUID userId) {
        return conversationRepository.findByConversationIdAndUserId(conversationId, userId)
                .orElseThrow(() -> new EntityNotFoundException(
                        "Conversation with given ID and user does not exist"));
    }
}
